-- 請在 Supabase Dashboard > SQL Editor 執行（可重複執行，已存在的不會重複插入）
-- 前置：必須先跑過 deity_feasts.sql 建表。
--
-- ── 這份資料的性質，動它之前務必先看 ──
-- 日期取自公開的「農曆神明生日表」對照（https://shenghong1126.com.tw/lunargods01/），
-- **不是廟方確認過的事實**。所以每一筆都插成 is_visible = FALSE（未顯示），
-- 廟方在後台逐筆核對後再自行開啟。前台在開啟前看不到任何一筆。
--
-- 已知的分歧，核對時要特別注意這幾筆：
--   太上老君   採二月十五（道德天尊）。同一份表在七月初一也列了太上老君，兩說並存。
--   九天玄女   採二月十五。八月十八亦有九天玄女娘娘之說。
--   鎮殿觀音   採二月十九（誕辰）。另有六月十九得道、九月十九出家，
--              廟方若是紀念得道或出家日，要改成對應的日期。
--   濟公三／五師父  採濟公菩薩二月初二。「三師父」「五師父」的序位是本壇的稱法，
--              對照表沒有分師父序位，若各有各的日子請廟方修正。
--   關聖帝君   採六月廿四。正月十三為飛昇、五月十三為關平帝君，不要混用。
--
-- ── 查不到、刻意不填的 11 尊 ──
-- 茉莉媽祖、天官武財神、老駕太子、九天司祿貴人星君、和緣太子、
-- 菁埔夫人、順天夫人、顧爐太子、黃府千歲、火神、天觀音
-- 其中多數是本壇特有或地方性的稱謂，外部對照表查不到；「天官武財神」是合稱
-- （上元天官正月十五、中路財神趙元帥三月十五），指哪一個要問廟方。
-- 猜一個填進去，錯了信眾會白跑一趟，所以留白由廟方補。

INSERT INTO public.deity_feasts
  (title, deity_id, calendar_type, lunar_month, lunar_day, is_leap_month, note, is_visible, sort_order)
SELECT v.title, d.id, 'lunar', v.m, v.dd, FALSE, '', FALSE, 0
FROM (VALUES
  ('天上大聖母', '天上大聖母聖誕', 3, 23),
  ('開基天上二聖母', '開基天上二聖母聖誕', 3, 23),
  ('天上三聖母', '天上三聖母聖誕', 3, 23),
  ('天上四聖母', '天上四聖母聖誕', 3, 23),
  ('天上五聖母', '天上五聖母聖誕', 3, 23),
  ('湄洲聖母', '湄洲聖母聖誕', 3, 23),
  ('太上老君', '太上老君聖誕', 2, 15),
  ('太乙救苦天尊', '太乙救苦天尊聖誕', 11, 11),
  ('王母娘娘', '王母娘娘聖誕', 7, 18),
  ('地母娘娘', '地母娘娘聖誕', 10, 18),
  ('九天玄女', '九天玄女聖誕', 2, 15),
  ('註生娘娘', '註生娘娘聖誕', 3, 20),
  ('關聖帝君', '關聖帝君聖誕', 6, 24),
  ('濟公三師父', '濟公三師父聖誕', 2, 2),
  ('濟公五師父', '濟公五師父聖誕', 2, 2),
  ('土地公', '土地公聖誕', 2, 2),
  ('鎮殿觀音', '鎮殿觀音聖誕', 2, 19),
  ('地藏王菩薩', '地藏王菩薩聖誕', 7, 30),
  ('玄天上帝', '玄天上帝聖誕', 3, 3),
  ('池府千歲', '池府千歲聖誕', 6, 18),
  ('虎爺', '虎爺聖誕', 6, 6),
  ('姜子牙', '姜子牙聖誕', 8, 3),
  ('范府千歲', '范府千歲聖誕', 4, 27),
  ('張天師', '張天師聖誕', 5, 18),
  ('法主公', '法主公聖誕', 7, 23),
  ('普賢王菩薩', '普賢王菩薩聖誕', 2, 21),
  ('文殊師利菩薩', '文殊師利菩薩聖誕', 4, 4)
) AS v(deity_name, title, m, dd)
-- LEFT JOIN：神尊名對不上時 deity_id 留 null，那一筆仍然建立（聖誕本身還是有效的）
LEFT JOIN public.deities d ON d.name = v.deity_name
WHERE NOT EXISTS (
  SELECT 1 FROM public.deity_feasts f WHERE f.title = v.title
);

-- 確認結果：應為 27 筆、全部未顯示；deity_id 對上幾筆也一併看
SELECT
  COUNT(*)                                   AS 總筆數,
  COUNT(*) FILTER (WHERE is_visible)         AS 已顯示,
  COUNT(*) FILTER (WHERE deity_id IS NOT NULL) AS 已對上神尊
FROM public.deity_feasts;
