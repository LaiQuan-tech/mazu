-- 捐獻補「收到了沒」的狀態（財務頁要用）
-- 請在 Supabase Dashboard > SQL Editor 執行（可重複執行）
--
-- ── 為什麼 ──
-- 廟方 2026-10-30 要做財務作業頁：「報名、捐款都會直接顯示在該頁，由財務去檢查，
-- 並點選『已收款』。」但**捐獻是全站唯一連「收到了沒」都沒有的收入**
-- （CLAUDE.md 早就記著：應收管理是唯讀報表、法會對帳只綁 fahui_registrations、
-- 捐獻連收到了沒都沒有）。沒有這一欄，財務頁就沒辦法把捐獻納進待辦清單。
--
-- ── 值與點燈／祈福／法會一致 ──
-- `待匯款` → `已收款`（`已取消`）。不要為捐獻另發明一組語彙，
-- 財務頁上四種收入並列，用語不一致就沒人看得懂哪個對應哪個。
--
-- ── **舊資料一律留 NULL，不要預設成「待匯款」** ──
-- 這是這支最重要的一條。歷史上的捐獻早就收到了，只是當初沒有地方記；
-- 把它們全部標成「待匯款」等於系統在宣稱「這些錢沒收到」——那是**憑空捏造的
-- 財務事實**，而且財務頁一打開就是一整頁假的待辦。
-- NULL 的意思是「當初沒有核對這件事」，與「還沒收到」是兩回事，畫面上要分開顯示。
--
-- 新的捐獻由程式在 insert 時明寫 `待匯款`（同 blessing_registrations 的作法：
-- **不要靠資料庫的 DEFAULT**，靠它等於每一筆新資料一出生就是預設值，
-- 日後改預設還要回頭追哪些是真的、哪些是預設來的）。
--
-- ── 感謝信不受影響 ──
-- 廟方 2026-10-30 決定：捐獻的感謝信**維持送出當下就寄**，不改成收到款才寄。
-- 隨喜捐獻的人送出後沒有任何回應，直到財務核對完，那個體驗會變差。
-- 所以這一欄純粹是給財務核對用的，與信眾那一端無關。

ALTER TABLE public.donations
  ADD COLUMN IF NOT EXISTS status text;

-- **刻意不建 CHECK**：這是報名的送出路徑，CHECK 一旦擋下來整筆捐獻就失敗，
-- 而追蹤欄位絕對不可以把轉換擋掉（同 utm_source_column.sql 與
-- lamp_blessing_payment_status.sql 的理由）。

COMMENT ON COLUMN public.donations.status IS
  '收款狀態：待匯款／已收款／已取消。NULL＝這筆是這個欄位存在之前的舊資料，當初沒有核對過，不等於未收款。';

